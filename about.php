            <h2>Frequently Asked <span class="gold-underline">Questions</span></h2>
            <p>Everything you need to know about gypsum false ceilings in Sri Lanka.</p>
        </div>

        <div class="faq-list reveal-on-scroll reveal-up delay-1">
            <div class="faq-item active">
                <div class="faq-question">
                    <span>How long does a gypsum false ceiling installation typically take?</span>
                    <i class="fa-solid fa-chevron-down faq-icon"></i>
                </div>
                <div class="faq-answer">
                    For a standard residential living room (around 300 to 500 sq ft), a multi-tiered false ceiling with cove framing and skim coat takes approximately <strong>3 to 5 working days</strong>. Entire homes or commercial floors are planned in phases so painting and lighting proceed without delays.
                </div>
            </div>

            <div class="faq-item">
                <div class="faq-question">
                    <span>Does a gypsum false ceiling reduce heat in Sri Lankan homes?</span>
                    <i class="fa-solid fa-chevron-down faq-icon"></i>
                </div>
                <div class="faq-answer">
                    Yes, significantly. Gypsum board naturally has low thermal conductivity. By creating a suspended air gap between the roof slab/asbestos/tiles and the false ceiling, heat transfer is drastically reduced, lowering indoor room temperatures by <strong>3°C to 5°C</strong> and reducing air conditioning electricity bills.
                </div>
            </div>

            <div class="faq-item">
                <div class="faq-question">
                    <span>Can gypsum ceilings support heavy ceiling fans and chandeliers?</span>
                    <i class="fa-solid fa-chevron-down faq-icon"></i>
                </div>
                <div class="faq-answer">
                    Yes. We never hang heavy fixtures directly from the gypsum plasterboard. Instead, our team installs heavy-gauge secondary steel suspension rods anchored directly into the concrete slab or roof trusses, allowing you to mount heavy crystal chandeliers, pendant lights, or fans with complete safety.
                </div>
            </div>

            <div class="faq-item">
                <div class="faq-question">
                    <span>What is the difference between standard and Moisture-Resistant (MR) boards?</span>
                    <i class="fa-solid fa-chevron-down faq-icon"></i>
                </div>
                <div class="faq-answer">
                    Standard gypsum boards (ivory paper) are ideal for living rooms, bedrooms, and offices. Moisture-Resistant (MR) boards (green paper) feature silicone-treated gypsum cores and water-repellent liners, making them essential for bathrooms, kitchens, balconies, and high-humidity coastal areas.
                </div>
            </div>

            <div class="faq-item">
                <div class="faq-question">
                    <span>Do you offer free on-site inspections and quotations?</span>
